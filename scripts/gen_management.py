def member(name: str) -> str:
    """A Java-legal member name for ``name``, keywords suffixed."""
    ident = camel(name)
    return f"{ident}Value" if ident in JAVA_KEYWORDS else ident


def snake(text: str) -> str:
    """``ServiceAccounts`` -> ``service_accounts``; already-snake input is kept."""
    out: list[str] = []
    for i, ch in enumerate(text):
        boundary = not text[i - 1].isupper() or (i + 1 < len(text) and text[i + 1].islower())
        if ch.isupper() and i and boundary:
            out.append("_")
        out.append(ch.lower())
    return "".join(out).replace("-", "_").replace("__", "_")


def safe(name: str) -> str:
    """A Python-legal identifier for ``name``, keywords suffixed."""
    ident = snake(name)
    return f"{ident}_" if ident in PY_KEYWORDS else ident


def wrap(text: str, width: int = 76) -> list[str]:
    """Reflow ``text`` into paragraph-preserving lines; ruff does not reflow docstrings."""
    out: list[str] = []
    for para in str(text).strip().split("\n\n"):
        words = para.split()
        if not words:
            continue
        line = ""
        for word in words:
            if line and len(line) + 1 + len(word) > width:
                out.append(line)
                line = word
            else:
                line = f"{line} {word}" if line else word
        if line:
            out.append(line)
        out.append("")
    while out and out[-1] == "":
        out.pop()
    return out


def escape(text: str) -> str:
    """Make a description from ``openapi.json`` safe to paste into KDoc.

    KDoc is Markdown, so backticks and most punctuation carry through
    untouched — the one thing that cannot is a ``*/``, which would close the
    comment early and leave the rest of the description as code. ``[`` and
    ``]`` are escaped because KDoc reads them as a link to a symbol, and a
    description mentioning ``[0, 1]`` would otherwise emit a dangling
    reference the Dokka gate reports.
    """
    out = " ".join(str(text).split())
    # Kotlin block comments NEST, so a `/*` anywhere inside KDoc opens a comment
    # that the block's own `*/` then closes -- leaving the real comment open and
    # swallowing the declaration below it. Both halves have to go.
    out = out.replace("*/", "*&#47;").replace("/*", "&#47;*")
    out = out.replace("[", "&#91;").replace("]", "&#93;")
    return out


def kdoc(text: str, indent: str = "", tags: list[str] | None = None) -> list[str]:
    """A wrapped KDoc block at ``indent``, with optional trailing tag lines."""
    body: list[str] = []
    for i, para in enumerate(str(text).split("\n\n")):
        if i:
            body.append("")
        body.extend(wrap(para, 96 - len(indent)))
    if tags:
        body.append("")
        for tag in tags:
            lines = wrap(tag, 92 - len(indent))
            body.append(lines[0])
            body.extend("    " + more for more in lines[1:])
    out = [f"{indent}/**"]
    out.extend(f"{indent} * {line}".rstrip() for line in body)
    out.append(f"{indent} */")
    return out


def inline_kdoc(text: str, indent: str = "") -> list[str]:
    """A one-line KDoc comment, or a wrapped block when it will not fit."""
    single = f"{indent}/** {text} */"
    if len(single) <= 100 and "\n" not in text:
        return [single]
    return kdoc(text, indent)


def resolve_ref(schema: Any) -> Any:
    """Follow ``$ref`` chains to the schema they name."""
    node = schema
    while isinstance(node, dict) and "$ref" in node:
        node = SCHEMAS.get(node["$ref"].split("/")[-1], {})
    return node


def nullable_ref(schema: Any) -> str | None:
    """``{oneOf: [{type: null}, {$ref: X}]}`` -- utoipa's optional-enum shape."""
    variants = schema.get("oneOf") if isinstance(schema, dict) else None
    if not isinstance(variants, list) or len(variants) != 2:
        return None
    nulls = [v for v in variants if v.get("type") == "null"]
    refs = [v for v in variants if "$ref" in v]
    return refs[0]["$ref"].split("/")[-1] if len(nulls) == 1 and len(refs) == 1 else None


def flatten(name: str) -> tuple[dict[str, Any], set[str], str | None]:
    """Properties, required set and description of ``name``, ``allOf`` resolved."""
    props: dict[str, Any] = {}
    required: set[str] = set()

    def absorb(node: Any) -> None:
        """Merge one ``allOf`` member's properties into the accumulator."""
        resolved = resolve_ref(node) if "$ref" in node else node
        props.update(resolved.get("properties") or {})
        required.update(resolved.get("required") or [])
        for sub in resolved.get("allOf") or []:
            absorb(sub)

    schema = SCHEMAS.get(name, {})
    absorb(schema)
    return props, required, schema.get("description")


def discriminated(schema: Any) -> tuple[str, list[tuple[str, Any]]] | None:
    """Detect an internally-tagged union and return ``(tag, [(value, payload)])``."""
    variants = schema.get("oneOf")
    if not isinstance(variants, list) or len(variants) < 2:
        return None
    tag: str | None = None
    arms: list[tuple[str, Any]] = []
    for variant in variants:
        parts = variant.get("allOf") or [variant]
        value: str | None = None
        payload: Any = None
        leftovers: dict[str, Any] = {"type": "object", "properties": {}, "required": []}
        for part in parts:
            if "$ref" in part:
                payload = part
                continue
            for pname, prop in (part.get("properties") or {}).items():
                enum = prop.get("enum")
                if prop.get("type") == "string" and isinstance(enum, list) and len(enum) == 1:
                    if tag and tag != pname:
                        return None
                    tag = pname
                    value = enum[0]
                else:
                    leftovers["properties"][pname] = prop
                    if pname in (part.get("required") or []):
                        leftovers["required"].append(pname)
        if value is None:
            return None
        arms.append((value, payload if payload is not None else leftovers))
    return (tag or "", arms)


def sensitive_map() -> dict[str, set[str]]:
    """Which fields of which schemas carry a secret, per the registry."""
    out: dict[str, set[str]] = {}
    for ns in REGISTRY["namespaces"].values():
        for op in ns["operations"].values():
            if op["request_schema"] and op["sensitive_request_fields"]:
                key = op["request_schema"].lstrip("[]")
                out.setdefault(key, set()).update(op["sensitive_request_fields"])
            if op["response"]["schema"] and op["sensitive_response_fields"]:
                key = op["response"]["schema"].lstrip("[]")
                out.setdefault(key, set()).update(op["sensitive_response_fields"])
    return out


def schema_closure() -> list[str]:
    """Every schema reachable from an operation, transitively, sorted."""
    seeds: set[str] = set()
    for ns in REGISTRY["namespaces"].values():
        for op in ns["operations"].values():
            if op["request_schema"]:
                seeds.add(op["request_schema"].lstrip("[]"))
            if op["response"]["schema"]:
                seeds.add(op["response"]["schema"].lstrip("[]"))

    def refs_in(node: Any, found: set[str]) -> None:
        """Collect every ``$ref`` target name appearing anywhere under ``node``."""
        if isinstance(node, list):
            for item in node:
                refs_in(item, found)
        elif isinstance(node, dict):
            if "$ref" in node:
                found.add(node["$ref"].split("/")[-1])
            for value in node.values():
                refs_in(value, found)

    seen: set[str] = set()
    frontier = list(seeds)
    while frontier:
        name = frontier.pop()
        if name in seen or name not in SCHEMAS:
            continue
        seen.add(name)
        found: set[str] = set()
        refs_in(SCHEMAS[name], found)
        frontier.extend(f for f in found if f not in seen)
    return sorted(seen)






