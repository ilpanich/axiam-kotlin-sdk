#!/usr/bin/env python3
"""Generate the CONTRACT §27 management surface for the Kotlin SDK.

Reads ``management-registry.json`` (the 146 operations across 24 namespaces,
maintained in ``ilpanich/axiam`` and vendored here) plus ``openapi.json`` for the
schemas those operations carry, and writes:

- ``src/main/kotlin/io/axiam/sdk/management/models/*.kt`` — one ``@Serializable``
  data class, enum or sealed interface per request and response type;
- ``src/main/kotlin/io/axiam/sdk/management/<Namespace>Api.kt`` — one namespace
  handle per namespace;
- ``src/main/kotlin/io/axiam/sdk/management/ManagementApi.kt`` — the accessors;
- ``src/test/kotlin/io/axiam/sdk/management/ManagementSurfaceGeneratedTest.kt``
- ``src/test/kotlin/io/axiam/sdk/management/ManagementSparseBodiesGeneratedTest.kt``
  — one conformance case per operation, plus the §27.9 assertion that all 146
  are reached.

Run with ``--check`` to verify the committed output is current; that is what CI
runs, so a registry change that is not regenerated fails the build rather than
shipping a surface that disagrees with the contract.

Kotlin removes the single largest source of generated bulk in the Java port:
a sparse body needs no builder, because every optional property defaults to
``null`` and ``encodeDefaults = false`` on the request writer omits anything
still holding its default. §27.4 rule 5 is therefore a property of the
serializer configuration rather than of 18 hand-rolled builders.
"""

