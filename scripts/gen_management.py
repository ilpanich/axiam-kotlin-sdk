KT_KEYWORDS = {
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun",
    "if", "in", "interface", "is", "null", "object", "package", "return",
    "super", "this", "throw", "true", "try", "typealias", "typeof", "val",
    "var", "when", "while",
}


def prop(name: str) -> str:
    """``resource_type`` -> ``resourceType``, backticked if it is a keyword."""
    out = camel(name)
    return f"`{out}`" if out in KT_KEYWORDS else out


def kotlin_type(schema: Any) -> str:
    """The Kotlin type for ``schema``, without nullability."""
    if not schema:
        return "JsonElement"
    if "$ref" in schema:
        return pascal(schema["$ref"].split("/")[-1])
    inner = nullable_ref(schema)
    if inner:
        return pascal(inner)
    if "oneOf" in schema or "anyOf" in schema:
        return "JsonElement"

    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), None)

    if kind == "string":
        if schema.get("format") == "uuid":
            return "@Serializable(with = UuidSerializer::class) UUID"
        if schema.get("format") == "date-time":
            return "@Serializable(with = InstantSerializer::class) Instant"
        return "String"
    if kind == "integer":
        return "Long" if schema.get("format") == "int64" else "Int"
    if kind == "number":
        return "Double"
    if kind == "boolean":
        return "Boolean"
    if kind == "array":
        return f"List<{kotlin_type(schema.get('items') or {})}>"
    if kind == "object":
        return "JsonElement"
    return "JsonElement"


def model_imports(rendered: str) -> list[str]:
    """The imports a generated model file needs, from what it actually renders."""
    wanted = [
        ("io.axiam.sdk.Sensitive", "Sensitive"),
        ("io.axiam.sdk.management.InstantSerializer", "InstantSerializer"),
        ("io.axiam.sdk.management.UuidSerializer", "UuidSerializer"),
        ("kotlinx.serialization.Contextual", "@Contextual"),
        ("kotlinx.serialization.SerialName", "@SerialName"),
        ("kotlinx.serialization.Serializable", "@Serializable"),
        ("kotlinx.serialization.json.JsonClassDiscriminator", "@JsonClassDiscriminator"),
        ("kotlinx.serialization.json.JsonElement", "JsonElement"),
        ("java.time.Instant", "Instant"),
        ("java.util.UUID", "UUID"),
    ]
    return sorted(fqn for fqn, token in wanted if token in rendered)


def header(rendered: str, package: str) -> str:
    """The banner, package line and derived imports for one generated file."""
    lines = [BANNER.rstrip("\n"), f"package {package}", ""]
    imports = model_imports(rendered)
    if imports:
        lines.extend(f"import {fqn}" for fqn in imports)
        lines.append("")
    return "\n".join(lines + [rendered]) + "\n"


def enum_constant(value: str) -> str:
    """``no_op_refresh`` -> ``NO_OP_REFRESH``; ``Active`` -> ``ACTIVE``."""
    out: list[str] = []
    for i, ch in enumerate(value):
        if ch in "-_ ":
            out.append("_")
            continue
        if ch.isupper() and i and value[i - 1].islower():
            out.append("_")
        out.append(ch.upper())
    ident = "".join(out)
    return f"_{ident}" if ident[:1].isdigit() else ident


def replacement_schemas() -> set[str]:
    """The request bodies whose PUT replaces rather than patches (§27.4 rule 5).

    Read from the registry's ``update_style`` rather than inferred from "every
    field is required", which is also true of most response types.
    """
    out: set[str] = set()
    for ns in REGISTRY["namespaces"].values():
        for op in ns["operations"].values():
            if op["update_style"] == "replace" and op["request_schema"]:
                out.add(op["request_schema"].lstrip("[]"))
    return out


def field_list(schema_name: str, secrets: set[str]) -> tuple[list[dict[str, Any]], set[str], str | None]:
    """The fields of a schema, in a stable order, with Kotlin names and types."""
    props, required, description = flatten(schema_name)
    fields = []
    for wire in sorted(props):
        fields.append({
            "wire": wire,
            "name": prop(wire),
            "type": "@Contextual Sensitive<String>" if wire in secrets else kotlin_type(props[wire]),
            "required": wire in required,
            "doc": props[wire].get("description") or f"the server's {wire} field",
            "secret": wire in secrets,
        })
    return fields, required, description


def emit_enum(name: str, schema: Any) -> str:
    """A Kotlin enum for a string-enum schema, with its wire spelling attached."""
    type_name = pascal(name)
    text = schema.get("description") or f"The {type_name} values the server uses."
    body = kdoc(escape(text) + "\n\nEach constant carries the spelling the server uses on the "
                "wire, so the Kotlin name can follow Kotlin's conventions without "
                "changing what is sent.")
    body.append("@Serializable")
    body.append(f"enum class {type_name} {{")
    values = schema["enum"]
    for i, value in enumerate(values):
        tail = "," if i < len(values) - 1 else ","
        body.append(f'    @SerialName("{value}")')
        body.append(f"    {enum_constant(value)}{tail}")
        if i < len(values) - 1:
            body.append("")
    body.append("}")
    return header("\n".join(body), MODELS_PACKAGE)


def emit_data_class(name: str, secrets: set[str], replacement: bool) -> str:
    """A ``@Serializable data class`` for an object schema."""
    type_name = pascal(name)
    fields, required, description = field_list(name, secrets)
    all_optional = bool(fields) and not required

    text = escape(description or f"The {type_name} schema from the server's OpenAPI document.")
    if all_optional:
        text += ("\n\nEvery property is optional, so this is a SPARSE body: what you leave "
                 "unset is left unchanged, and is omitted from the wire request entirely "
                 "rather than sent as null (§27.4 rule 5). Naming the properties you mean to "
                 "change is the whole API — there is no builder because Kotlin does not need "
                 "one, and no way to accidentally send a field you did not name.")
    elif replacement:
        text += ("\n\nThis body REPLACES rather than patches (§27.4 rule 5): what you do not "
                 "carry over from a prior read is not preserved, it is overwritten. Every "
                 "property is required and none defaults, so forgetting one is a compile "
                 "error rather than a silent null on the wire. Read first, copy(), write "
                 "back.")

    tags = []
    for f in fields:
        doc = escape(f["doc"])
        if f["secret"]:
            doc += (" -- SECRET: redacted from toString and from every rendering except the "
                    "one request body it is sent in")
        tags.append(f"@property {f['name'].strip('`')} {doc}")

    body: list[str] = kdoc(text, "", tags)
    body.append("@Serializable")
    if not fields:
        body.append(f"class {type_name}")
        return header("\n".join(body), MODELS_PACKAGE)

    body.append(f"data class {type_name}(")
    for f in fields:
        default = "" if f["required"] else " = null"
        nullable = "" if f["required"] else "?"
        body.append(f'    @SerialName("{f["wire"]}") val {f["name"]}: {f["type"]}{nullable}{default},')
    body.append(")")
    return header("\n".join(body), MODELS_PACKAGE)


def emit_union(name: str, schema: Any, tag: str, arms: list[tuple[str, Any]]) -> dict[str, str]:
    """A sealed interface plus one data class per arm, discriminated on ``tag``."""
    type_name = pascal(name)
    files: dict[str, str] = {}
    arm_names = [f"{type_name}{pascal(value)}" for value, _ in arms]

    lines = kdoc(
        escape(schema.get("description") or f"A {type_name} value.")
        + f"\n\nA closed set of shapes discriminated by the {tag} field. Sealed, so a "
          f"`when` over the permitted arms is exhaustive and the compiler says so — which "
          f"is what makes adding an arm a compile error at every call site rather than a "
          f"silent fall-through.")
    lines.append("@Serializable")
    lines.append(f'@JsonClassDiscriminator("{tag}")')
    lines.append(f"sealed interface {type_name}")
    files[f"{MODELS_DIR}/{type_name}.kt"] = header("\n".join(lines), MODELS_PACKAGE)

    for (value, payload), arm in zip(arms, arm_names):
        if "$ref" in payload:
            props, required, desc = flatten(payload["$ref"].split("/")[-1])
        else:
            props = payload.get("properties") or {}
            required = set(payload.get("required") or [])
            desc = payload.get("description")
        fields = [{
            "wire": w, "name": prop(w), "type": kotlin_type(props[w]),
            "required": w in required,
            "doc": props[w].get("description") or f"the server's {w} field",
        } for w in sorted(props) if w != tag]

        tags = [f"@property {f['name'].strip('`')} {escape(f['doc'])}" for f in fields]
        arm_lines = kdoc(escape(desc or f"The '{value}' arm of {type_name}."), "", tags or None)
        arm_lines.append("@Serializable")
        arm_lines.append(f'@SerialName("{value}")')
        if not fields:
            arm_lines.append(f"class {arm} : {type_name}")
        else:
            arm_lines.append(f"data class {arm}(")
            for f in fields:
                default = "" if f["required"] else " = null"
                nullable = "" if f["required"] else "?"
                arm_lines.append(
                    f'    @SerialName("{f["wire"]}") val {f["name"]}: {f["type"]}{nullable}{default},')
            arm_lines.append(f") : {type_name}")
        files[f"{MODELS_DIR}/{arm}.kt"] = header("\n".join(arm_lines), MODELS_PACKAGE)
    return files


def emit_models() -> dict[str, str]:
    """Every generated model file, keyed by repository-relative path."""
    secrets = sensitive_map()
    replacements = replacement_schemas()
    files: dict[str, str] = {}
    for name in schema_closure():
        schema = SCHEMAS[name]
        if "enum" in schema and schema.get("type") == "string":
            files[f"{MODELS_DIR}/{pascal(name)}.kt"] = emit_enum(name, schema)
            continue
        union = discriminated(schema)
        if union:
            files.update(emit_union(name, schema, union[0], union[1]))
            continue
        files[f"{MODELS_DIR}/{pascal(name)}.kt"] = emit_data_class(
            name, secrets.get(name, set()), name in replacements)
    return files


