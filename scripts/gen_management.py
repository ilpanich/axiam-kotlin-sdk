def path_param_names(op: dict[str, Any]) -> list[str]:
    """This operation's path parameter names, in path order."""
    return [p["name"] for p in op["path_params"]]


def implicit_params(namespace: str, op: dict[str, Any]) -> set[str]:
    """Which of this operation's path params default from the client (§27.4 rule 3)."""
    out: set[str] = set()
    for param in path_param_names(op):
        if param == "org_id":
            out.add(param)
        elif param == "tenant_id" and namespace in IMPLICIT_TENANT_NAMESPACES:
            out.add(param)
    return out


def split_query(op: dict[str, Any]) -> tuple[list[str], list[str]]:
    """This operation's query parameter NAMES, split into paging and the rest.

    ``offset``/``limit`` are handled by [PageRequest] rather than surfaced as
    two loose integers, so they never become parameters of the generated
    function.
    """
    names = [q["name"] for q in op["query_params"]]
    paging = [n for n in names if n in ("offset", "limit")]
    other = [n for n in names if n not in ("offset", "limit")]
    return paging, other


def operation_params(namespace: str, opname: str, op: dict[str, Any]) -> list[dict[str, str]]:
    """The Kotlin parameter list for one generated operation, in order."""
    implicit = implicit_params(namespace, op)
    params: list[dict[str, str]] = []
    for param in path_param_names(op):
        if param in implicit:
            continue
        params.append({
            "name": prop(param),
            "type": "UUID",
            "wire": param,
            "doc": f"the {param.replace('_', ' ')} to address",
        })
    if op["request_schema"]:
        schema = op["request_schema"].lstrip("[]")
        params.append({
            "name": "body",
            "type": pascal(schema),
            "wire": "",
            "doc": "the request body",
        })
    _, other = split_query(op)
    for query in other:
        params.append({
            "name": prop(query),
            "type": "String?",
            "wire": query,
            "doc": f"the optional {query.replace('_', ' ')} filter, or null to omit it",
        })
    if op["paginated"]:
        params.append({
            "name": "page",
            "type": "PageRequest?",
            "wire": "",
            "doc": "where to start and how many to ask for, or null for the server's default",
        })
    return params


def response_kotlin(op: dict[str, Any]) -> tuple[str, str]:
    """The declared return type, and how the body is decoded into it.

    Driven by the registry's ``response.kind``, which is the authoritative
    statement of the shape. The ``schema`` field never carries an ``[]``
    prefix, so inferring array-ness from the name silently turns all thirteen
    bare-array reads into single objects -- the exact confusion §27.4 rule 4
    exists to prevent.
    """
    kind, schema = op["response"]["kind"], op["response"]["schema"]
    if kind == "none" or not schema:
        return "Unit", "unit"
    model = pascal(schema)
    if kind == "page":
        return f"Page<{model}>", "page"
    if kind == "array":
        return f"List<{model}>", "list"
    return model, "one"


def spec_description(op: dict[str, Any]) -> str | None:
    """The prose openapi.json carries for this route, if any.

    The registry's own ``summary`` is only ever ``"METHOD /path"``, which
    restates the line above it. The spec's ``description`` is the one place
    that says what the operation actually does.
    """
    entry = SPEC.get("paths", {}).get(op["path"], {}).get(op["method"].lower())
    if not isinstance(entry, dict):
        return None
    text = entry.get("description")
    return escape(text) if text else None


def operation_doc(op: dict[str, Any], canonical: str) -> str:
    """The KDoc body for one generated operation."""
    prose = spec_description(op)
    route = f"`{op['method']} {op['path']}`"
    lines = [f"{prose}\n\nIssues {route}." if prose else f"Issues {route}."]
    if op["paginated"]:
        lines.append(
            "\n\nPaginated: `total` on the returned page is the size of the WHOLE set, not "
            "of this page (§27.4 rule 4). Use `" + canonical.split(".")[1] +
            "All(...)` to walk every page.")
    if op["update_style"] == "sparse":
        lines.append(
            "\n\nA SPARSE update: the properties you leave unset are omitted from the wire "
            "body entirely and left unchanged (§27.4 rule 5).")
    elif op["update_style"] == "replace":
        lines.append(
            "\n\nA REPLACEMENT, not a patch: every field of the body is written, so read the "
            "current value first and `copy()` the parts you mean to keep (§27.4 rule 5).")
    if op["method"] != "GET":
        lines.append(
            "\n\nNot retried: §27.4 rule 8 makes every write on this surface single-shot, "
            "including the ones that look idempotent.")
    return "".join(lines)


def emit_operation(namespace: str, opname: str, op: dict[str, Any]) -> list[str]:
    """One generated suspend function on a namespace handle."""
    canonical = f"{namespace}.{opname}"
    params = operation_params(namespace, opname, op)
    ret, shape = response_kotlin(op)
    implicit = implicit_params(namespace, op)

    tags = [f"@param {p['name'].strip('`')} {p['doc']}" for p in params]
    if ret != "Unit":
        tags.append(f"@return {'the page of results' if shape == 'page' else 'the server response'}")

    lines = kdoc(operation_doc(op, canonical), "    ", tags)
    signature = ", ".join(f"{p['name']}: {p['type']}" for p in params)
    declared = "" if ret == "Unit" else f": {ret}"
    lines.append(f"    suspend fun {prop(opname)}({signature}){declared} {{")

    # Path interpolation. An implicit param resolves from the client or the
    # handle's own override, and fails locally when neither has one.
    for param in sorted(implicit):
        resolver = "resolveOrg" if param == "org_id" else "resolveTenant"
        lines.append(f'        val {prop(param)} = ManagementSupport.{resolver}('
                     f'transport, scope, "{canonical}")')

    path = op["path"]
    for param in path_param_names(op):
        path = path.replace("{" + param + "}", "${" + prop(param) + "}")
    lines.append(f'        val path = "{path}"')

    _, other = split_query(op)
    if other or op["paginated"]:
        entries = ", ".join(f'"{q}" to {prop(q)}' for q in other)
        base = f"mapOf({entries})" if other else "emptyMap()"
        if op["paginated"]:
            lines.append(f"        val query = ManagementSupport.pageQuery({base}, page)")
        else:
            lines.append(f"        val query = {base}")
    body_arg = ""
    if op["request_schema"]:
        schema = op["request_schema"].lstrip("[]")
        lines.append(f'        val payload = ManagementSupport.encodeBody('
                     f'"{canonical}", {pascal(schema)}.serializer(), body)')
        body_arg = ", body = payload"

    query_arg = ", query = query" if (other or op["paginated"]) else ""
    lines.append(("        transport.send(" if shape == "unit" else "        val node = transport.send("))
    lines.append(f'            operation = "{canonical}",')
    lines.append(f'            method = "{op["method"]}",')
    lines.append(f'            pathTemplate = "{op["path"]}",')
    lines.append(f"            path = path{query_arg}{body_arg},")
    lines.append("        )")

    if shape == "page":
        model = ret[len("Page<"):-1]
        lines.append(f'        return ManagementSupport.decodePage('
                     f'"{canonical}", {model}.serializer(), node)')
    elif shape == "list":
        model = ret[len("List<"):-1]
        lines.append(f'        return ManagementSupport.decodeList('
                     f'"{canonical}", {model}.serializer(), node)')
    elif shape == "one":
        lines.append(f'        return ManagementSupport.decode('
                     f'"{canonical}", {ret}.serializer(), node)')
    lines.append("    }")

    if op["paginated"]:
        lead = [p for p in params if p["name"] != "page"]
        sig = ", ".join(f"{p['name']}: {p['type']}" for p in lead)
        sig = (sig + ", " if sig else "") + "start: PageRequest? = null"
        call = ", ".join(p["name"] for p in lead)
        call = (call + ", " if call else "") + "it"
        model = ret[len("Page<"):-1]
        all_tags = [f"@param {p['name'].strip('`')} {p['doc']}" for p in lead]
        all_tags.append("@param start the first window to request, or null for the server's default")
        all_tags.append("@return every item, in the server's order")
        lines.append("")
        lines.extend(kdoc(
            f"Walks `{prop(opname)}` to exhaustion and returns every item (§27.4 rule 4)."
            "\n\nStops on an empty page even when the server's `total` disagrees, so a "
            "misreporting server costs one wasted request rather than an unbounded loop.",
            "    ", all_tags))
        lines.append(f"    suspend fun {prop(opname)}All({sig}): List<{model}> =")
        lines.append(f"        ManagementSupport.collectPages(start) {{ {prop(opname)}({call}) }}")
    return lines


def emit_namespace(namespace: str, nsdef: dict[str, Any]) -> str:
    """One namespace handle: a view over the client, with its operations."""
    type_name = f"{pascal(namespace)}Api"
    has_org = any("org_id" in implicit_params(namespace, op) for op in nsdef["operations"].values())
    has_tenant = any("tenant_id" in implicit_params(namespace, op)
                     for op in nsdef["operations"].values())

    text = escape(nsdef.get("description") or f"The {namespace} management operations.")
    text += ("\n\nA view over the client that created it, not a connection: constructing one "
             "performs no I/O (§27.2 rule 1), so there is nothing to cache and nothing to "
             "close.")
    lines = kdoc(text)
    lines.append(f"class {type_name} internal constructor(")
    lines.append("    private val transport: ManagementTransport,")
    lines.append("    private val scope: NamespaceScope = NamespaceScope.inherited(),")
    lines.append(") {")
    lines.append("")

    if has_org:
        lines.extend(kdoc(
            "Returns a handle addressing [orgId] instead of the client's organization.\n\n"
            "A NEW handle: this one is unchanged, so a scoped call cannot leak into "
            "unrelated code holding the same reference (§27.4 rule 3).",
            "    ", ["@param orgId the organization to address",
                    f"@return a {type_name} scoped to [orgId]"]))
        lines.append(f"    fun inOrg(orgId: UUID): {type_name} =")
        lines.append(f"        {type_name}(transport, scope.copy(orgId = orgId))")
        lines.append("")
    if has_tenant:
        lines.extend(kdoc(
            "Returns a handle addressing [tenantId] instead of the client's tenant.\n\n"
            "A NEW handle: this one is unchanged (§27.4 rule 3).",
            "    ", ["@param tenantId the tenant to address",
                    f"@return a {type_name} scoped to [tenantId]"]))
        lines.append(f"    fun forTenant(tenantId: UUID): {type_name} =")
        lines.append(f"        {type_name}(transport, scope.copy(tenantId = tenantId))")
        lines.append("")

    for opname, op in nsdef["operations"].items():
        lines.extend(emit_operation(namespace, opname, op))
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("}")

    rendered = "\n".join(lines)
    body = [BANNER.rstrip("\n"), f"package {API_PACKAGE}", ""]
    imports = {"io.axiam.sdk.internal.ManagementTransport"}
    if "UUID" in rendered:
        imports.add("java.util.UUID")
    # Derived by intersecting the capitalised words in the CODE with the set of
    # type names the models package actually exports. An earlier cut matched a
    # regex against the whole file and imported `models.This` out of a KDoc
    # sentence; prose and code cannot be told apart by shape, only by whether
    # the word names something that exists.
    code = "\n".join(line for line in rendered.splitlines()
                     if not line.lstrip().startswith(("*", "/**")))
    models = model_type_names()
    imports.update(f"{MODELS_PACKAGE}.{name}" for name in
                   {n for n in re.findall(r"\b([A-Z][A-Za-z0-9]*)\b", code) if n in models})
    body.extend(f"import {fqn}" for fqn in sorted(imports))
    body.append("")
    return "\n".join(body + [rendered]) + "\n"


