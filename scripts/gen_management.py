def example_json(schema: Any, depth: int = 0) -> Any:
    """A minimal JSON value satisfying ``schema``, for a mounted response."""
    if depth > 6:
        return None
    if "$ref" in schema:
        return example_for(schema["$ref"].split("/")[-1], depth + 1)
    inner = nullable_ref(schema)
    if inner:
        return example_for(inner, depth + 1)
    if "oneOf" in schema or "anyOf" in schema:
        return {}
    if "enum" in schema:
        return schema["enum"][0]
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), None)
    if kind == "array":
        return []
    if kind == "integer":
        return 1
    if kind == "number":
        return 1.0
    if kind == "boolean":
        return True
    if kind == "object":
        return {}
    if kind == "string":
        if schema.get("format") == "uuid":
            return EXAMPLE_UUID
        if schema.get("format") == "date-time":
            return EXAMPLE_TIME
        return "example"
    return None


def example_for(name: str, depth: int = 0) -> Any:
    """A minimal JSON object satisfying the named schema."""
    schema = SCHEMAS.get(name, {})
    if "enum" in schema and schema.get("type") == "string":
        return schema["enum"][0]
    union = discriminated(schema)
    if union:
        tag, arms = union
        value, payload = arms[0]
        body = {tag: value}
        if "$ref" in payload:
            props, required, _ = flatten(payload["$ref"].split("/")[-1])
        else:
            props = payload.get("properties") or {}
            required = set(payload.get("required") or [])
        for wire in sorted(props):
            if wire != tag and wire in required:
                body[wire] = example_json(props[wire], depth + 1)
        return body
    props, required, _ = flatten(name)
    return {w: example_json(props[w], depth + 1) for w in sorted(props) if w in required}


def example_response(op: dict[str, Any]) -> str:
    """The JSON body a mounted route answers this operation with.

    Shaped by the registry's ``response.kind``, the same authority
    [response_kotlin] reads. Deriving one from ``kind`` and the other from the
    schema name is how a bare-array route ends up mounted with a bare object.
    """
    kind, schema = op["response"]["kind"], op["response"]["schema"]
    if kind == "none" or not schema:
        return '""'
    item = example_for(schema)
    if kind == "page":
        payload: Any = {"items": [item], "total": 1, "offset": 0, "limit": 200}
    elif kind == "array":
        payload = [item]
    else:
        payload = item
    return json.dumps(json.dumps(payload))


def kotlin_literal(schema: Any, secrets: set[str], field: str | None = None, depth: int = 0) -> str:
    """A Kotlin expression building a minimal valid value for a schema."""
    if depth > 6:
        return "null"
    if field and field in secrets:
        return 'Sensitive.of("example")'
    if "$ref" in schema:
        return literal_for(schema["$ref"].split("/")[-1], set(), depth + 1)
    if nullable_ref(schema) or "oneOf" in schema or "anyOf" in schema or "enum" in schema:
        return "null"
    kind = schema.get("type")
    if isinstance(kind, list):
        if "null" in kind:
            return "null"
        kind = next(iter(kind), None)
    if kind == "array":
        return "emptyList()"
    if kind == "integer":
        return "1L" if schema.get("format") == "int64" else "1"
    if kind == "number":
        return "1.0"
    if kind == "boolean":
        return "true"
    if kind == "string":
        if schema.get("format") == "uuid":
            return "EXAMPLE_ID"
        if schema.get("format") == "date-time":
            return f'java.time.Instant.parse("{EXAMPLE_TIME}")'
        return '"example"'
    return "null"


def literal_for(name: str, secrets: set[str], depth: int = 0) -> str:
    """A Kotlin expression constructing a minimal valid instance of ``name``."""
    schema = SCHEMAS.get(name, {})
    type_name = f"{MODELS_PACKAGE}.{pascal(name)}"
    if "enum" in schema and schema.get("type") == "string":
        return f"{type_name}.{enum_constant(schema['enum'][0])}"
    union = discriminated(schema)
    if union:
        tag, arms = union
        value, payload = arms[0]
        arm = f"{type_name}{pascal(value)}"
        if "$ref" in payload:
            aprops, arequired, _ = flatten(payload["$ref"].split("/")[-1])
        else:
            aprops = payload.get("properties") or {}
            arequired = set(payload.get("required") or [])
        args = [f"{prop(w)} = {kotlin_literal(aprops[w], set(), w, depth + 1)}"
                for w in sorted(aprops) if w != tag and w in arequired]
        return f"{arm}({', '.join(args)})"
    props, required, _ = flatten(name)
    args = []
    for wire in sorted(props):
        if wire in secrets:
            args.append(f'{prop(wire)} = Sensitive.of("example")')
        elif wire in required:
            args.append(f"{prop(wire)} = {kotlin_literal(props[wire], secrets, wire, depth + 1)}")
    return f"{type_name}({', '.join(args)})"


def call_arguments(namespace: str, opname: str, op: dict[str, Any],
                   secrets: dict[str, set[str]]) -> tuple[list[str], str]:
    """The arguments the conformance case passes, and the path it must reach."""
    implicit = implicit_params(namespace, op)
    args: list[str] = []
    route = op["path"]
    for param in path_param_names(op):
        if param == "org_id" and param in implicit:
            route = route.replace("{org_id}", "$ORG_ID")
            continue
        if param == "tenant_id" and param in implicit:
            route = route.replace("{tenant_id}", "$TENANT_ID")
            continue
        args.append(f"{prop(param)} = EXAMPLE_ID")
        route = route.replace("{" + param + "}", "$EXAMPLE_ID")
    if op["request_schema"]:
        schema = op["request_schema"].lstrip("[]")
        args.append(f"body = {literal_for(schema, secrets.get(schema, set()))}")
    _, other = split_query(op)
    for query in other:
        args.append(f"{prop(query)} = null")
    if op["paginated"]:
        args.append("page = PageRequest.of(50)")
    return args, route


